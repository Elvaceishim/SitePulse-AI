
import json

from pydantic import ValidationError

from app.models.briefing import BriefingNarrative
from app.models.intervention import InterventionDraft
from app.services.llm_client import OpenRouterClient, OpenRouterError
from app.services.summary_generator import generate_executive_summary


class BriefingGenerationError(Exception):
    """Raised when a briefing cannot be generated or validated."""


SYSTEM_PROMPT = """
You are an operational intelligence assistant helping workplace
safety supervisors understand and prioritise operational risks.

You receive structured risk assessments and recommendations
generated by a deterministic rules engine.

Your task is to synthesise the information into a useful
supervisor briefing.

STRICT RULES:

1. Use only information supplied in the input data.
2. Never invent hazards, incidents, symptoms, causes, or outcomes.
3. Never diagnose medical conditions or predict health outcomes.
4. Never calculate or modify risk scores.
5. Never change priority bands or urgency levels.
6. Never create new safety recommendations.
7. Never claim that a risk causes an outcome unless the input
   explicitly establishes that relationship.
8. Distinguish reported risk levels from calculated priority bands.
9. Identify stale assessments and explain why their information
   requires verification.
10. Do not describe synthetic data as real operational data.

EXECUTIVE SUMMARY:
- Do not write or calculate the executive summary.
- The application generates it separately.
- You must still include the executive_summary field
  in your JSON response.
- Set its value to "Generated by application logic."

SITE SUMMARIES:
- Produce exactly one summary per supplied site.
- Include the site_id provided in the input.
- Include every assessment_id associated with that site.
- Do not include assessment IDs belonging to another site.
- Account for every supplied assessment.
- Mention only risk categories associated with that site.
- Explain the site's most important operational concerns.
- Do not invent facts or change priority classifications.

INTERVENTION NOTES:
- Produce exactly one explanation per supplied assessment.
- Explain why the assessment has its assigned priority.
- Refer to the actual risk category, site context,
  assessment score, and freshness status where useful.
- Do not repeat the recommended action.
- Do not repeat the priority band without explaining
  its relevance.
- Do not predict consequences or outcomes.
- Do not claim that an assessment will affect worker
  health, safety, productivity, or operations unless
  the input explicitly establishes that relationship.
- Do not introduce new hazards, causes, or facts.
- For stale assessments, explain that the information
  requires verification before it is relied upon.
- Keep each explanation to one or two sentences.

Keep the writing concise, clear, and useful to a supervisor.

Return valid JSON only, without Markdown code fences.

Use this exact structure:

{
  "executive_summary": "Generated by application logic.",
  "site_summaries": [
    {
      "site_id": "UUID",
      "assessment_ids": [
        "UUID"
      ],
      "summary": "A concise site summary."
    }
  ],
  "intervention_notes": [
    {
      "assessment_id": "UUID",
      "priority_explanation": "Why this assessment deserves its priority."
    }
  ]
}
"""


class BriefingGenerator:

    def __init__(self, client=None):
        self.client = client or OpenRouterClient()

    @staticmethod
    def _prepare_input(
        interventions: list[InterventionDraft],
    ) -> dict:

        sites = {}
        assessment_records = []

        for item in interventions:
            risk = item.risk
            site = risk.site
            assessment = risk.assessment

            sites[str(site.id)] = {
                "site_id": str(site.id),
                "name": site.name,
                "location": site.location,
                "industry": site.industry,
                "workforce_size": site.workforce_size,
            }

            assessment_records.append({
                "site_id": str(site.id),
                "site_name": site.name,
                "assessment_id": str(assessment.id),
                "category": assessment.category.value,
                "score": assessment.score,
                "reported_risk_level": assessment.risk_level.value,
                "priority_band": risk.priority_band.value,
                "description": assessment.description,
                "observed_at": assessment.observed_at.isoformat(),
                "age_hours": risk.age_hours,
                "is_stale": risk.is_stale,
                "source": assessment.source,
                "data_is_synthetic": assessment.data_is_synthetic,
                "urgency": item.urgency,
                "recommended_action": item.recommended_action,
                "rationale": item.rationale,
                "data_warning": item.data_warning,
            })

        return {
            "sites": list(sites.values()),
            "assessments": assessment_records,
        }

    @staticmethod
    def _validate_references(
        briefing: BriefingNarrative,
        interventions: list[InterventionDraft],
    ):

        # Build the expected relationship between sites
        # and their associated assessments.
        expected_site_assessments = {}

        for item in interventions:
            site_id = item.risk.site.id
            assessment_id = item.risk.assessment.id

            expected_site_assessments.setdefault(
                site_id, set()
            ).add(assessment_id)

        expected_site_ids = set(expected_site_assessments)

        expected_assessment_ids = {
            assessment_id
            for assessment_ids in expected_site_assessments.values()
            for assessment_id in assessment_ids
        }

        # Validate site references.
        returned_site_ids = [
            item.site_id
            for item in briefing.site_summaries
        ]

        if len(returned_site_ids) != len(set(returned_site_ids)):
            raise BriefingGenerationError(
                "The briefing contains duplicate site references."
            )

        if set(returned_site_ids) != expected_site_ids:
            raise BriefingGenerationError(
                "The briefing contains missing or unknown site references."
            )

        # Validate assessment references in site summaries.
        returned_site_assessment_ids = []

        for site_summary in briefing.site_summaries:
            assessment_ids = site_summary.assessment_ids

            if len(assessment_ids) != len(set(assessment_ids)):
                raise BriefingGenerationError(
                    "The briefing contains duplicate assessment references."
                )

            expected_ids = expected_site_assessments[site_summary.site_id]

            if set(assessment_ids) != expected_ids:
                raise BriefingGenerationError(
                    "A site summary contains missing or incorrectly assigned assessments."
                )

            returned_site_assessment_ids.extend(assessment_ids)

        if len(returned_site_assessment_ids) != len(
            set(returned_site_assessment_ids)
        ):
            raise BriefingGenerationError(
                "The briefing contains duplicate assessment references."
            )

        if set(returned_site_assessment_ids) != expected_assessment_ids:
            raise BriefingGenerationError(
                "Site summaries contain missing or unknown assessment references."
            )

        # Validate intervention note references.
        returned_assessment_ids = [
            item.assessment_id
            for item in briefing.intervention_notes
        ]

        if len(returned_assessment_ids) != len(set(returned_assessment_ids)):
            raise BriefingGenerationError(
                "The briefing contains duplicate assessment references."
            )

        if set(returned_assessment_ids) != expected_assessment_ids:
            raise BriefingGenerationError(
                "The briefing contains missing or unknown assessment references."
            )

    def generate(
        self,
        interventions: list[InterventionDraft],
    ) -> BriefingNarrative:

        if not interventions:
            raise ValueError(
                "At least one intervention is required."
            )

        payload = self._prepare_input(interventions)

        executive_summary = generate_executive_summary(
            interventions
        )

        messages = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": (
                    "Generate a supervisor briefing from this data:\n"
                    + json.dumps(payload, indent=2)
                ),
            },
        ]

        try:
            response = self.client.generate(
                messages=messages,
                temperature=0.1,
                max_tokens=2000,
            )

        except OpenRouterError as exc:
            raise BriefingGenerationError(
                "The AI briefing request failed."
            ) from exc

        try:
            briefing = BriefingNarrative.model_validate_json(response)

            # Replace the LLM's placeholder with the
            # authoritative application-generated summary.
            briefing.executive_summary = executive_summary

        except (ValidationError, ValueError) as exc:
            raise BriefingGenerationError(
                "The AI returned invalid briefing JSON."
            ) from exc

        # Validate all site and assessment relationships.
        self._validate_references(
            briefing,
            interventions,
        )

        return briefing
